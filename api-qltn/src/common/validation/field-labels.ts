/** Labels are keyed by the field name; nested paths (`taskDueDays.APPROVE_PROPOSAL`) use the last segment. */
export const fieldLabel = (field: string): string => {
  const segments = field.split('.');
  const last = segments[segments.length - 1] ?? field;
  return FIELD_LABELS[last] ?? FIELD_LABELS[field] ?? last;
};
